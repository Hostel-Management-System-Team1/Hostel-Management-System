"""The receipt as a PDF (HMS-F-012)."""

from io import BytesIO

from django.utils import timezone
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle


def money(value):
    return f"Rs. {value:,.2f}"


def receipt_pdf(receipt):
    """Return the PDF bytes for a receipt."""
    invoice = receipt.invoice
    resident = invoice.resident
    styles = getSampleStyleSheet()
    title = ParagraphStyle("title", parent=styles["Title"], alignment=0, fontSize=20)
    body = styles["BodyText"]
    buffer = BytesIO()
    document = SimpleDocTemplate(
        buffer, pagesize=A4, leftMargin=20 * mm, rightMargin=20 * mm, topMargin=18 * mm,
        title=f"Receipt {receipt.number}", author="Hostel Management System",
    )
    story = [
        Paragraph("Hostel Management System", styles["Heading3"]),
        Paragraph(f"Payment receipt {receipt.number}", title),
        Spacer(1, 6 * mm),
    ]
    issued = timezone.localtime(receipt.issued_at).strftime("%d %b %Y, %H:%M")
    details = [
        ["Receipt number", receipt.number, "Date", issued],
        ["Invoice", invoice.number, "Payment method", receipt.payment.get_method_display()],
        ["Received from", resident.get_full_name() or resident.username, "Gateway reference",
         receipt.payment.gateway_ref or "-"],
    ]
    table = Table(details, colWidths=[35 * mm, 50 * mm, 38 * mm, 47 * mm])
    table.setStyle(TableStyle([
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("TEXTCOLOR", (0, 0), (0, -1), colors.grey),
        ("TEXTCOLOR", (2, 0), (2, -1), colors.grey),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]))
    story += [table, Spacer(1, 8 * mm), Paragraph(invoice.description, body), Spacer(1, 3 * mm)]
    rows = [["Item", "Amount"]] + [[i.description, money(i.amount)] for i in invoice.items.all()]
    rows.append(["Total paid", money(receipt.amount)])
    items = Table(rows, colWidths=[120 * mm, 50 * mm])
    items.setStyle(TableStyle([
        ("FONTSIZE", (0, 0), (-1, -1), 10),
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e8ebf0")),
        ("ALIGN", (1, 0), (1, -1), "RIGHT"),
        ("LINEBELOW", (0, 0), (-1, -2), 0.25, colors.lightgrey),
        ("LINEABOVE", (0, -1), (-1, -1), 1, colors.black),
        ("FONTNAME", (0, -1), (-1, -1), "Helvetica-Bold"),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    story += [items, Spacer(1, 10 * mm), Paragraph(
        "This receipt was generated by the system and is valid without a signature. "
        "No card or bank details are stored by the Hostel Management System.", styles["Italic"])]
    document.build(story)
    return buffer.getvalue()
